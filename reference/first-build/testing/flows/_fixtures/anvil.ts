import { Address, Hex, TransactionHash } from "@floor/contract";
import { Deferred, Effect, FileSystem, Option, Schema, Stream } from "effect";
import { ChildProcess } from "effect/process";
import { createPublicClient, createTestClient, createWalletClient, http, parseAbi } from "viem";
import { privateKeyToAccount } from "viem/accounts";
import { baseSepolia } from "viem/chains";

export class AnvilFlowError
  extends Schema.TaggedError<AnvilFlowError>()("AnvilFlowError", { message: Schema.String })
{}
export const chainCall = <A>(description: string, run: () => Promise<A>) =>
  Effect.tryPromise({
    try: run,
    catch: () => new AnvilFlowError({ message: description }),
  });
const Credentials = Schema.Struct({ private_keys: Schema.Tuple([TransactionHash, TransactionHash, TransactionHash]) });
const Artifact = Schema.Struct({ bytecode: Schema.Struct({ object: Hex }) });
export const bytecode = Effect.fn("Flow.bytecode")(function*(artifact: string) {
  const fs = yield* FileSystem.FileSystem;
  const file = yield* fs.readFileString(`packages/foundry/out/${artifact}.json`);
  return (yield* Schema.decodeEffect(Schema.fromJsonString(Artifact))(file)).bytecode.object;
});

export const scopedAccountAbi = parseAbi([
  "constructor(address owner_, address session_)",
  "function grant(bytes32 id, address target, bytes4 selector, uint256 maximumValue, uint256 expiresAt, bytes32 calldataHash)",
  "function execute(bytes32 id, address target, uint256 value, bytes data) returns (bytes)",
  "function ownerCall(address target, uint256 value, bytes data) returns (bytes)",
  "function withdrawToOwner(uint256 amount)",
]);
export const curveAbi = parseAbi([
  "function buy(uint256 minimumTokens) payable",
  "function sell(uint256 tokenAmount, uint256 minimumEth)",
  "function graduate()",
  "function graduated() view returns (bool)",
  "function token() view returns (address)",
]);
export const tokenAbi = parseAbi([
  "function transfer(address to, uint256 amount) returns (bool)",
  "function approve(address spender, uint256 amount) returns (bool)",
  "function transferFrom(address from, address to, uint256 amount) returns (bool)",
  "function unlockAt() view returns (uint256)",
  "function balanceOf(address account) view returns (uint256)",
]);

/** @stability unstable */
export const openAnvil = Effect.fn("Flow.openAnvil")(function*() {
  const fs = yield* FileSystem.FileSystem;
  const directory = yield* fs.makeTempDirectoryScoped({ prefix: "floor-anvil-flow-" });
  const build = yield* ChildProcess.make("forge", ["build", "--root", "packages/foundry"], {
    stdout: "ignore",
    stderr: "inherit",
    forceKillAfter: "5 seconds",
  });
  if ((yield* build.exitCode) !== 0) {
    return yield* new AnvilFlowError({ message: "The real launch contracts did not compile." });
  }
  const ready = yield* Deferred.make<string>();
  const process = yield* ChildProcess.make("anvil", [
    "--host",
    "127.0.0.1",
    "--port",
    "0",
    "--chain-id",
    "84532",
    "--accounts",
    "3",
    "--mnemonic-random",
    "--config-out",
    `${directory}/accounts.json`,
  ], { stdout: "pipe", stderr: "inherit", forceKillAfter: "5 seconds" });
  yield* process.stdout.pipe(
    Stream.decodeText,
    Stream.splitLines,
    Stream.runForEach((line) =>
      line.startsWith("Listening on 127.0.0.1:")
        ? Deferred.succeed(ready, `http://${line.slice("Listening on ".length).trim()}`).pipe(Effect.asVoid)
        : Effect.void
    ),
    Effect.forkScoped,
  );
  const url = yield* Deferred.await(ready).pipe(Effect.timeout("15 seconds"));
  const credentials = yield* fs.readFileString(`${directory}/accounts.json`).pipe(
    Effect.flatMap(Schema.decodeUnknownEffect(Schema.fromJsonString(Credentials))),
  );
  // Keys are newly generated by this scoped local node; no caller-supplied RPC URL or external signing key can enter the flow.
  const transport = http(url, { retryCount: 0, timeout: 10_000 });
  const chain = createPublicClient({ chain: baseSepolia, transport });
  const control = createTestClient({ chain: baseSepolia, transport, mode: "anvil" });
  if ((yield* chainCall("Local chain identity was not Base Sepolia", () => chain.getChainId())) !== 84532) {
    return yield* new AnvilFlowError({ message: "The isolated node's chain identity was wrong." });
  }
  const owner = createWalletClient({
    chain: baseSepolia,
    transport,
    account: privateKeyToAccount(credentials.private_keys[0]),
  });
  const session = createWalletClient({
    chain: baseSepolia,
    transport,
    account: privateKeyToAccount(credentials.private_keys[1]),
  });
  const buyer = createWalletClient({
    chain: baseSepolia,
    transport,
    account: privateKeyToAccount(credentials.private_keys[2]),
  });
  const accountCode = yield* bytecode("ScopedAccountFixture.sol/ScopedAccountFixture");
  const hash = yield* chainCall("Deploying the isolated scoped account failed", () =>
    owner.deployContract({
      abi: scopedAccountAbi,
      bytecode: accountCode,
      args: [owner.account.address, session.account.address],
    }));
  const receipt = yield* chainCall(
    "The isolated account deployment was not mined",
    () => chain.waitForTransactionReceipt({ hash }),
  );
  const address = yield* Schema.decodeUnknownEffect(Address)(
    Option.getOrUndefined(Option.fromNullishOr(receipt.contractAddress)),
  );
  const funded = yield* chainCall(
    "The local scoped account could not be funded",
    () => owner.sendTransaction({ to: address, value: 10n ** 19n }),
  );
  yield* chainCall(
    "The local funding receipt was unavailable",
    () => chain.waitForTransactionReceipt({ hash: funded }),
  );
  return { chain, control, owner, session, buyer, address, url };
});
