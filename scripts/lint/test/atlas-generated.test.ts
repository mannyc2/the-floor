const fixture = Effect.gen(function*() {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const root = yield* fs.makeTempDirectoryScoped({ prefix: "floor-atlas-" });
  for (const file of sourcePaths) {
    const target = path.join(root, file);
    yield* fs.makeDirectory(path.dirname(target), { recursive: true });
    yield* fs.writeFileString(target, yield* fs.readFileString(file));
  }
  yield* fs.makeDirectory(path.join(root, "apps/web/src"), { recursive: true });
  yield* fs.writeFileString(path.join(root, "apps/web/index.html"), "<!doctype html><title>Atlas fixture</title>\n");
  yield* buildAtlas(root);
  return root;
});

const checkStyles = Effect.fn("Atlas.testStyles")(function*(root: string) {
  const path = yield* Path.Path;
  const spawner = yield* ChildProcessSpawner.ChildProcessSpawner;
  const process = yield* spawner.spawn(ChildProcess.make("bun", [path.resolve("scripts/lint/styles.ts")], {
    cwd: root,
    stdout: "ignore",
    stderr: "ignore",
    forceKillAfter: "5 seconds",
  }));
  return yield* process.exitCode;
});

test("generation is deterministic and only its verified outputs receive a style exemption", () =>
  runTest(
    Effect.gen(function*() {
      const fs = yield* FileSystem.FileSystem;
      const path = yield* Path.Path;
      const root = yield* fixture;
      expect([...yield* verifyGeneratedAtlas(root)]).toEqual(outputPaths);
      expect(yield* checkStyles(root)).toBe(ChildProcessSpawner.ExitCode(0));
      const first = yield* fs.readFileString(path.join(root, manifestPath));
      yield* buildAtlas(root);
      expect(yield* fs.readFileString(path.join(root, manifestPath))).toBe(first);
      yield* fs.writeFileString(
        path.join(root, "apps/web/src/copied-atlas.css"),
        "/* Generated by scripts/build-atlas.ts */ :root { color: #ffffff; }\n",
      );
      expect(yield* checkStyles(root)).not.toBe(ChildProcessSpawner.ExitCode(0));
    }),
    BunServices.layer,
  ));

test("source changes and missing, added or edited outputs fail the generated manifest fence", () =>
  runTest(
    Effect.gen(function*() {
      const fs = yield* FileSystem.FileSystem;
      const path = yield* Path.Path;
      for (const mutation of ["source", "edit", "missing", "extra", "bom-source", "bom-output"]) {
        const root = yield* fixture;
        const css = path.join(root, "packages/atlas/generated/atlas.css");
        if (mutation === "source") {
          const file = path.join(root, "packages/atlas/src/tokens.ts");
          yield* fs.writeFileString(file, (yield* fs.readFileString(file)) + "\n// source drift\n");
        }
        if (mutation === "edit") yield* fs.writeFileString(css, "/* same filename is not authority */\n");
        if (mutation === "missing") yield* fs.remove(css);
        if (mutation === "bom-source" || mutation === "bom-output") {
          const file = mutation === "bom-source" ? path.join(root, "packages/atlas/src/tokens.ts") : css;
          const original = yield* fs.readFile(file);
          yield* fs.writeFile(file, new Uint8Array([239, 187, 191, ...original]));
        }
        if (mutation === "extra") {
          yield* fs.writeFileString(path.join(root, "packages/atlas/generated/other.css"), ":root { color: #fff }\n");
        }
        expect(Result.isFailure(yield* verifyGeneratedAtlas(root).pipe(Effect.result))).toBe(true);
      }
    }),
    BunServices.layer,
  ));

test("editing an output and its digest cannot bless hand-authored generated values", () =>
  runTest(
    Effect.gen(function*() {
      const fs = yield* FileSystem.FileSystem;
      const path = yield* Path.Path;
      const root = yield* fixture;
      const file = "packages/atlas/generated/atlas.css";
      const content = ":root { --atlas-ground: #ff0000; }\n";
      yield* fs.writeFileString(path.join(root, file), content);
      const manifestFile = path.join(root, manifestPath);
      const manifest = yield* fs.readFileString(manifestFile).pipe(
        Effect.flatMap(Schema.decodeEffect(AtlasManifestJson)),
      );
      const crypto = yield* Crypto.Crypto;
      const sha256 = Hex.encode(yield* crypto.digest("SHA-256", new TextEncoder().encode(content)));
      const edited = {
        ...manifest,
        outputs: manifest.outputs.map(output => output.path === file ? { ...output, sha256 } : output),
      };
      yield* fs.writeFileString(manifestFile, yield* Schema.encodeEffect(AtlasManifestJson)(edited));
      const result = yield* verifyGeneratedAtlas(root).pipe(Effect.result);
      expect(Result.isFailure(result)).toBe(true);
      if (Result.isFailure(result)) expect(result.failure._tag).toBe("AtlasGeneratedError");
    }),
    BunServices.layer,
  ));

test("manifest inventory cannot drop sources, outputs or source attribution", () =>
  runTest(
    Effect.gen(function*() {
      const fs = yield* FileSystem.FileSystem;
      const path = yield* Path.Path;
      for (const mutation of ["sources", "outputs", "attribution"]) {
        const root = yield* fixture;
        const file = path.join(root, manifestPath);
        const original = yield* fs.readFileString(file).pipe(Effect.flatMap(Schema.decodeEffect(AtlasManifestJson)));
        const edited = {
          ...original,
          sources: mutation === "sources" ? original.sources.slice(1) : original.sources,
          outputs: mutation === "outputs" ? original.outputs.slice(1) : original.outputs.map(output => ({
            ...output,
            sources: mutation === "attribution" ? [] : output.sources,
          })),
        };
        yield* fs.writeFileString(file, yield* Schema.encodeEffect(AtlasManifestJson)(edited));
        expect(Result.isFailure(yield* verifyGeneratedAtlas(root).pipe(Effect.result))).toBe(true);
      }
    }),
    BunServices.layer,
  ));

test("the generated manifest rejects byte edits even when its decoded meaning is unchanged", () =>
  runTest(
    Effect.gen(function*() {
      const fs = yield* FileSystem.FileSystem;
      const path = yield* Path.Path;
      for (const mutation of ["bom", "whitespace", "unknown-property"]) {
        const root = yield* fixture;
        const file = path.join(root, manifestPath);
        const content = yield* fs.readFileString(file);
        if (mutation === "bom") {
          yield* fs.writeFile(file, new Uint8Array([239, 187, 191, ...new TextEncoder().encode(content)]));
        }
        if (mutation === "whitespace") yield* fs.writeFileString(file, content + "\n");
        if (mutation === "unknown-property") {
          yield* fs.writeFileString(file, content.replace("{", "{\"untracked\": \"edit\","));
        }
        const result = yield* verifyGeneratedAtlas(root).pipe(Effect.result);
        expect(Result.isFailure(result)).toBe(true);
        if (Result.isFailure(result)) {
          expect(result.failure._tag).toBe("AtlasGeneratedError");
        }
      }
    }),
    BunServices.layer,
  ));

const unitInterval = Schema.Finite.check(Schema.isBetween({ minimum: 0, maximum: 1 }));
const metadata = { $extensions: Schema.Record(Schema.String, Schema.Json) };
const DtcgToken = Schema.Union([
  Schema.Struct({
    $type: Schema.Literal("color"),
    $value: Schema.Struct({
      colorSpace: Schema.Literal("srgb"),
      components: Schema.Tuple([unitInterval, unitInterval, unitInterval]),
      alpha: unitInterval,
    }),
    ...metadata,
  }),
  Schema.Struct({ $type: Schema.Literal("number"), $value: Schema.Finite, ...metadata }),
  Schema.Struct({
    $type: Schema.Literal("dimension"),
    $value: Schema.Struct({ value: Schema.Finite, unit: Schema.Literal("px") }),
    ...metadata,
  }),
  Schema.Struct({
    $type: Schema.Literal("duration"),
    $value: Schema.Struct({ value: Schema.Finite, unit: Schema.Literal("ms") }),
    ...metadata,
  }),
]);
const collectTokens = (node: Schema.Json): Array<Schema.Json> => {
  const group = Schema.decodeUnknownOption(Schema.JsonObject)(node);
  if (Option.isNone(group)) return [];
  if ("$value" in group.value) return [group.value];
  return Object.entries(group.value).filter(([key]) => !key.startsWith("$")).flatMap(([, value]) =>
    collectTokens(value)
  );
};

test("DTCG 2025.10 values use typed color components and preserve per-value status", () =>
  runTest(
    Effect.gen(function*() {
      const tokens = collectTokens(dtcgTokens);
      expect(tokens.length).toBeGreaterThan(0);
      const statuses = new Set<string>();
      for (const token of tokens) {
        const decoded = yield* Schema.decodeUnknownEffect(DtcgToken)(token);
        const provenance = yield* Schema.decodeUnknownEffect(
          Schema.Struct({ status: Schema.Struct({ _tag: Schema.Literals(["Approved", "Provisional", "Synthetic"]) }) }),
        )(decoded.$extensions["org.the-floor.atlas"]);
        statuses.add(provenance.status._tag);
      }
      expect(statuses).toEqual(new Set(["Approved", "Provisional", "Synthetic"]));
    }),
    BunServices.layer,
  ));

test("linear texture rows contain every palette address with opaque RGBA channels", () => {
  for (const theme of ["day", "night"]) {
    if (theme !== "day" && theme !== "night") continue;
    const row = linearPalette(paletteValues, theme);
    expect(row).toHaveLength(PaletteName.literals.length * 4);
    for (let index = 0; index < row.length; index++) {
      const value = row[index];
      expect(value).toBeGreaterThanOrEqual(0);
      expect(value).toBeLessThanOrEqual(1);
      if (index % 4 === 3) expect(value).toBe(1);
    }
    const ground = row.slice(0, 3);
    expect(ground.some(value => value !== Math.round(value * 255) / 255)).toBe(true);
  }
});
